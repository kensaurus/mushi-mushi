'use client'

/**
 * The fix-prompt actions on the sample diagnosis page, mirroring the console's
 * "Fix it with your coding agent" panel (apps/admin/src/components/report-detail/FixWithAgentPanel.tsx):
 *   - Copy fix prompt: the whole prompt (buildFixPrompt).
 *   - Open in Cursor: Cursor's prompt deeplink carrying the shorter,
 *     URL-capped copy (buildUrlFixPrompt), as the console does.
 *   - Claude Code: the console has no Claude Code deeplink; its lane is
 *     "copy, run `claude` in your project folder, paste", so this is too.
 * Both prompt strings come from data/sample-fix-prompt.json, generated by the
 * console's own builder and guarded by fixPrompt.sample.test.ts.
 */
import { useState } from 'react'

interface SampleFixActionsProps {
  fixPrompt: string
  urlFixPrompt: string
}

/** Same shape as the console's buildCursorDeeplink. */
function cursorDeeplink(prompt: string): string {
  return `cursor://anysphere.cursor-deeplink/prompt?prompt=${encodeURIComponent(prompt)}`
}

export function SampleFixActions({ fixPrompt, urlFixPrompt }: SampleFixActionsProps) {
  const [copied, setCopied] = useState(false)
  const [claudeOpen, setClaudeOpen] = useState(false)

  function copy() {
    void navigator.clipboard?.writeText(fixPrompt).then(() => {
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    })
  }

  return (
    <div className="sample-dx__actions">
      <div className="sample-dx__action-row">
        <button
          type="button"
          className="landing-hero-cta landing-hero-cta--primary"
          onClick={copy}
          data-mushi-cta="sample-copy-fix-prompt"
          data-mushi-location="sample-diagnosis"
        >
          {copied ? 'Copied' : 'Copy fix prompt'}
        </button>
        <a
          className="landing-hero-cta landing-hero-cta--secondary"
          href={cursorDeeplink(urlFixPrompt)}
          data-mushi-cta="sample-open-cursor"
          data-mushi-location="sample-diagnosis"
        >
          Open in Cursor
        </a>
        <button
          type="button"
          className="landing-hero-cta landing-hero-cta--secondary"
          aria-expanded={claudeOpen}
          aria-controls="sample-dx-claude"
          onClick={() => setClaudeOpen(!claudeOpen)}
          data-mushi-cta="sample-claude-code"
          data-mushi-location="sample-diagnosis"
        >
          Use with Claude Code
        </button>
      </div>
      <p className="sample-dx__note">
        {(fixPrompt.length / 1000).toFixed(1)}k characters. Paste it into Claude Code, Cursor, Codex, Windsurf or
        any other coding agent; it needs no Mushi setup. Open in Cursor carries a shorter copy, because a link can
        only hold so much.
      </p>
      {claudeOpen ? (
        <ol id="sample-dx-claude" className="sample-dx__claude">
          <li>
            Click <strong>Copy fix prompt</strong>.
          </li>
          <li>
            In your project folder run <code>claude</code> and paste it.
          </li>
        </ol>
      ) : null}
    </div>
  )
}
