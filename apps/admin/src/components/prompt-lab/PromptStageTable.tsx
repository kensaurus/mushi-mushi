import { Card, Badge, Btn, RelativeTime } from '../ui'
import { ConfigHelp } from '../ConfigHelp'
import {
  IconCopy,
  IconPencil,
  IconDiff,
  IconSliders,
  IconTrash,
} from '../icons'
import type { PromptVersion } from './types'
import { STAGE_LABELS, isCustomizablePromptStage } from './types'
import { CHIP_TONE } from '../../lib/chipTone'
import { effectiveTraffic } from './promptLabCounts'
import { VersionStateMark } from './VersionStateMark'
import { useMediaQuery } from '../../lib/useMediaQuery'
import { BarCell, type BarTone } from '../signal/BarCell'

// Icon-only Btn override for the dense action column.
//
// Each prompt row carries up to six controls (Clone / Edit / Diff /
// Activate / Traffic / Delete) and the previous text-only treatment
// caused a 250 px wall of verbs that wrapped on tablet widths and
// drowned the row metadata. Compressing the secondaries to glyphs
// while keeping the text label on the *primary* forward action
// (Activate — the only verb that truly progresses the workflow loop)
// matches the "icons + tooltip for secondaries, text for primaries"
// rule the Btn JSDoc spells out and recovers the row to a single
// horizontal scan.
//
// `!px-1.5` shrinks the BTN_SIZES.sm `px-2` to a square inset so the
// glyph reads as a button face, not a left-aligned icon with empty
// trailing space. Tooltips + aria-labels are mandatory — without them
// the column becomes a screen-reader trap.
const ICON_BTN = '!px-1.5'

/**
 * Domain-local tone ramp for judge scores (0.80 ok / 0.60 warn / <0.60 danger).
 * Mirrors JudgePage's ScorePill so an 0.80 eval is green in both views. We
 * intentionally don't delegate to ui.tsx#Pct / tokens.ts#pctToneClass here —
 * those use a 90/70 ramp tuned for health success rates / uptime, which
 * recolours legitimate 0.80–0.89 judge scores from green to amber. See the
 * comment in JudgePage#ScorePill for the full rationale.
 */
function judgeScoreTone(score: number): BarTone {
  if (score >= 0.8) return 'ok'
  if (score >= 0.6) return 'warn'
  return 'danger'
}

/** A grade as a bar on the 0–100 scale, or a dash with no grades. */
function GradeBar({ score }: { score: number | null }) {
  // A dash: the status line says "no grades" once (2026-11-19: four times).
  if (score == null) return <span className="text-fg-faint text-2xs" title="No grades yet">—</span>
  const pct = Math.round(score * 100)
  return <BarCell value={pct} max={100} text={`${pct}%`} tone={judgeScoreTone(score)} widthClass="w-12" />
}

interface PromptStageTableProps {
  stage: string
  prompts: PromptVersion[]
  busy: string | null
  onClone: (p: PromptVersion) => void
  onEdit: (p: PromptVersion) => void
  onDiff: (p: PromptVersion) => void
  onActivate: (p: PromptVersion) => void
  onTraffic: (p: PromptVersion) => void
  onDelete: (p: PromptVersion) => void
}

export function PromptStageTable({
  stage,
  prompts,
  busy,
  onClone,
  onEdit,
  onDiff,
  onActivate,
  onTraffic,
  onDelete,
}: PromptStageTableProps) {
  // Phone: one stacked row per version; the table scrolled sideways and cut State to "Candi"
  // (2026-11-19).
  const wide = useMediaQuery('(min-width: 640px)', true)

  const renderState = (p: PromptVersion) => (
    <>
      <VersionStateMark version={p} detailed />
      {p.project_id == null && (
        <Badge className="ml-1 bg-surface-overlay text-fg-secondary border border-edge-subtle" title="Built-in version shared by every app; clone it to edit.">Global</Badge>
      )}
      {p.auto_generated && (
        <Badge
          className={`ml-1 ${CHIP_TONE.brandSubtle}`}
          title={p.auto_generation_metadata?.changeSummary ?? 'Generated by prompt-auto-tune'}
        >
          Auto
        </Badge>
      )}
    </>
  )

  const renderActions = (p: PromptVersion) => {
    const isGlobal = p.project_id == null
    return (
      <>
      {isCustomizablePromptStage(stage) ? (
        <Btn
          size="sm"
          variant="ghost"
          className={ICON_BTN}
          disabled={busy === p.id}
          onClick={() => onClone(p)}
          title="Clone — create an editable copy"
          aria-label={`Clone prompt ${p.version}`}
        >
          <IconCopy />
        </Btn>
      ) : (
        <span
          className="text-2xs text-fg-faint"
          title="No worker reads a project copy of this prompt yet, so it cannot be customised."
        >
          Built-in
        </span>
      )}
      {!isGlobal && (
        <>
          <Btn
            size="sm"
            variant="ghost"
            className={ICON_BTN}
            disabled={busy === p.id}
            onClick={() => onEdit(p)}
            title="Edit prompt template"
            aria-label={`Edit prompt ${p.version}`}
          >
            <IconPencil />
          </Btn>
          {p.parent_version_id && (
            <Btn
              size="sm"
              variant="ghost"
              className={ICON_BTN}
              disabled={busy === p.id}
              onClick={() => onDiff(p)}
              title="Diff against parent prompt"
              aria-label={`Diff prompt ${p.version} against its parent`}
            >
              <IconDiff />
            </Btn>
          )}
          {!p.is_active && (
            // Activate stays text — it's the page's
            // primary forward action and "Activate" is
            // a one-way swap of the live prompt; the
            // explicit verb is the safety rail.
            <Btn
              size="sm"
              variant="success"
              disabled={busy === p.id}
              onClick={() => onActivate(p)}
              title="Use this version for every report in this step"
            >
              Switch to this
            </Btn>
          )}
          {!p.is_active && (
            <Btn
              size="sm"
              variant="ghost"
              className={ICON_BTN}
              disabled={busy === p.id}
              onClick={() => onTraffic(p)}
              title="Choose how many reports this version tests on"
              aria-label={`Choose how many reports ${p.version} tests on`}
            >
              <IconSliders />
            </Btn>
          )}
          <Btn
            size="sm"
            variant="danger"
            className={ICON_BTN}
            disabled={busy === p.id || p.is_active}
            onClick={() => onDelete(p)}
            title="Delete prompt"
            aria-label={`Delete prompt ${p.version}`}
          >
            <IconTrash />
          </Btn>
        </>
      )}
      </>
    )
  }

  if (!wide && prompts.length > 0) {
    return (
      <Card elevated className="min-w-0 p-3">
        <div className="flex items-center justify-between mb-2">
          <h3 className="text-xs font-semibold text-fg-secondary">{STAGE_LABELS[stage] ?? stage}</h3>
          <span className="text-2xs text-fg-faint tabular-nums">{prompts.length} versions</span>
        </div>
        <ul className="divide-y divide-edge-subtle text-2xs" data-testid="prompt-stage-rows">
          {prompts.map((p) => {
            const score = p.avg_judge_score
            return (
              <li key={p.id} className="space-y-1 py-2">
                <div className="flex min-w-0 flex-wrap items-center gap-x-2 gap-y-1">
                  {renderState(p)}
                  <span className="min-w-0 break-all font-mono text-2xs text-fg-muted" data-testid="prompt-version-id">{p.version}</span>
                </div>
                <p className="flex flex-wrap items-center gap-x-3 text-fg-muted tabular-nums">
                  <GradeBar score={score} />
                  <span>{p.total_evaluations} grades</span>
                  <span>{effectiveTraffic(p, prompts)}% of reports</span>
                  <RelativeTime value={p.updated_at} />
                </p>
                <div className="flex flex-wrap items-center gap-1">{renderActions(p)}</div>
              </li>
            )
          })}
        </ul>
      </Card>
    )
  }

  return (
    <Card elevated className="min-w-0 p-3">
      <div className="flex items-center justify-between mb-2">
        <h3 className="text-xs font-semibold text-fg-secondary">
          {STAGE_LABELS[stage] ?? stage}
        </h3>
        <span className="text-2xs text-fg-faint tabular-nums">
          {prompts.length} versions
        </span>
      </div>
      {prompts.length === 0 ? (
        <p className="text-2xs text-fg-faint">No prompts registered for this stage.</p>
      ) : (
        // A 390px card is narrower than version ids such as
        // v1-baseline-auto-20261028 plus the action buttons. `truncate`
        // ellipsized the id and let the table shrink to the card, so
        // overflow-x never had anything to scroll. The table keeps its
        // content width; this region scrolls.
        <div className="min-w-0 overflow-x-auto overscroll-x-contain">
          <table className="w-full min-w-max text-2xs">
            <thead className="text-fg-faint">
              <tr>
                <th className="whitespace-nowrap text-left font-normal px-2 py-1">State</th>
                <th className="whitespace-nowrap text-left font-normal px-2 py-1">Version</th>
                <th className="whitespace-nowrap text-left font-normal px-2 py-1">Grade</th>
                <th className="whitespace-nowrap text-right font-normal px-2 py-1">Grades</th>
                <th className="whitespace-nowrap text-left font-normal px-2 py-1">
                  <span className="inline-flex items-center gap-1">
                    Share of reports
                    <ConfigHelp helpId="prompt-lab.traffic_percentage" />
                  </span>
                </th>
                <th className="whitespace-nowrap text-left font-normal px-2 py-1">Updated</th>
                <th className="whitespace-nowrap text-right font-normal px-2 py-1">Actions</th>
              </tr>
            </thead>
            <tbody>
              {prompts.map((p) => {
                const score = p.avg_judge_score
                const share = effectiveTraffic(p, prompts)
                return (
                  <tr key={p.id} className="border-t border-edge-subtle">
                    <td className="whitespace-nowrap px-2 py-1.5">
                      {/* The same mark as Triage grading, with the share in words. */}
                      {renderState(p)}
                    </td>
                    <td className="whitespace-nowrap px-2 py-1.5 font-mono text-2xs text-fg-muted" data-testid="prompt-version-id">
                      {p.version}
                    </td>
                    <td className="px-2 py-1.5" title="Average grade from Triage grading; higher is better.">
                      <GradeBar score={score} />
                    </td>
                    <td className="px-2 py-1.5 text-right text-fg-muted tabular-nums">
                      {p.total_evaluations}
                    </td>
                    <td
                      className="px-2 py-1.5"
                      title={p.is_active
                        ? `Keeps ${share}% of reports: what the tests do not take.`
                        : `Gets ${share}% of reports; the version in use keeps the rest.`}
                    >
                      {/* A deliberate split, not a quality signal: a neutral bar. */}
                      <BarCell value={share} max={100} text={`${share}%`} widthClass="w-12" />
                    </td>
                    <td className="px-2 py-1.5 text-fg-muted">
                      <RelativeTime value={p.updated_at} />
                    </td>
                    <td className="px-2 py-1.5 text-right space-x-1 whitespace-nowrap">
                      {renderActions(p)}
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        </div>
      )}
    </Card>
  )
}
