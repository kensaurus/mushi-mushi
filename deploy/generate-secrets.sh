#!/usr/bin/env bash
# FILE: deploy/generate-secrets.sh
# PURPOSE: Write deploy/.env for docker-compose.yml with fresh random secrets,
#          and anon / service_role JWTs signed with JWT_SECRET (the Supabase
#          self-host generate-keys pattern). Values are never printed.
#
# Usage:   ./deploy/generate-secrets.sh                 # writes deploy/.env
#          MUSHI_PUBLIC_URL=https://mushi.example.com ./deploy/generate-secrets.sh
#          FORCE=1 ./deploy/generate-secrets.sh         # replace (rotates every secret)
# Windows / no openssl: npx mushi-mushi selfhost secrets  (same output)
set -euo pipefail

cd "$(dirname "$0")"
OUT="${1:-.env}"
PUBLIC_URL="${MUSHI_PUBLIC_URL:-http://localhost}"

if [ -e "$OUT" ] && [ "${FORCE:-}" != "1" ]; then
  echo "✗ deploy/$OUT already exists. Set FORCE=1 to replace it (this rotates every secret)." >&2
  exit 1
fi
command -v openssl >/dev/null 2>&1 || {
  echo "✗ openssl not found. Use: npx mushi-mushi selfhost secrets" >&2
  exit 1
}

rand() { openssl rand -hex "$1"; }
b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }
jwt() {
  local role="$1" secret="$2" now exp header payload sig
  now=$(date +%s)
  exp=$((now + 5 * 365 * 24 * 3600))
  header=$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)
  payload=$(printf '{"role":"%s","iss":"supabase","iat":%d,"exp":%d}' "$role" "$now" "$exp" | b64url)
  sig=$(printf '%s.%s' "$header" "$payload" | openssl dgst -sha256 -hmac "$secret" -binary | b64url)
  printf '%s.%s.%s' "$header" "$payload" "$sig"
}

JWT_SECRET=$(rand 32)
umask 077
cat >"$OUT" <<EOF
# Generated by deploy/generate-secrets.sh. Keep this file private; never commit it.
# Public address of the stack (Caddy serves the console and the API here).
MUSHI_PUBLIC_URL=${PUBLIC_URL}
MUSHI_SITE_ADDRESS=${PUBLIC_URL}

# Required: generated, do not edit by hand (the JWTs below are signed with JWT_SECRET).
POSTGRES_PASSWORD=$(rand 24)
JWT_SECRET=${JWT_SECRET}
SUPABASE_ANON_KEY=$(jwt anon "$JWT_SECRET")
SUPABASE_SERVICE_ROLE_KEY=$(jwt service_role "$JWT_SECRET")
MUSHI_INTERNAL_CALLER_SECRET=$(rand 32)

# Optional: one LLM key turns on the plain-English diagnosis and fix drafts.
# Either provider works. Leave both empty for rule-based triage only.
ANTHROPIC_API_KEY=
OPENAI_API_KEY=
EOF

echo "✓ Wrote deploy/$OUT (mode 600)."
echo "  Generated: POSTGRES_PASSWORD, JWT_SECRET, SUPABASE_ANON_KEY, SUPABASE_SERVICE_ROLE_KEY, MUSHI_INTERNAL_CALLER_SECRET"
echo "  Optional:  ANTHROPIC_API_KEY or OPENAI_API_KEY (edit the file)"
