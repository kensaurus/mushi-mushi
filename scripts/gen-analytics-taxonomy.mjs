#!/usr/bin/env node
/**
 * FILE: scripts/gen-analytics-taxonomy.mjs
 * PURPOSE: Generate the Deno mirror of packages/core/src/analytics-taxonomy.ts
 *          so edge functions validate the same event vocabulary the SDK ships.
 *
 * USAGE:
 *   node scripts/gen-analytics-taxonomy.mjs          # write
 *   node scripts/gen-analytics-taxonomy.mjs --check  # exit 1 when stale (CI)
 *
 * The parser is deliberately naive: it reads the `MUSHI_EVENTS` block line by
 * line and expects `name: { surface: 'x' | ['x', 'y'], required: [...] },` per
 * line, plus the EVENT_NAME_RE / EVENT_PROPERTY_LIMITS / MUSHI_SURFACES
 * literals. An entry it cannot parse, or an unknown surface, is an error.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'

const ROOT = resolve(new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const SRC = resolve(ROOT, 'packages/core/src/analytics-taxonomy.ts')
const OUT = resolve(ROOT, 'packages/server/supabase/functions/_shared/analytics-taxonomy.generated.ts')
const check = process.argv.includes('--check')

const src = readFileSync(SRC, 'utf8')

function grab(re, label) {
  const m = src.match(re)
  if (!m) throw new Error(`gen-analytics-taxonomy: could not find ${label} in ${SRC}`)
  return m[1]
}

const nameRe = grab(/export const EVENT_NAME_RE = (\/[^\n]+\/[a-z]*);/, 'EVENT_NAME_RE')
// Module-private in the SDK source (only sanitizeEventProperties uses it), but
// the Deno mirror exports it for the ingest route — so match with or without
// the `export` keyword.
const piiRe = grab(/(?:export\s+)?const PII_PROPERTY_KEY_RE = (\/[^\n]+\/[a-z]*);/, 'PII_PROPERTY_KEY_RE')
const surfaces = grab(/export const MUSHI_SURFACES = \[([^\]]+)\] as const;/, 'MUSHI_SURFACES')
  .split(',').map((s) => s.trim().replace(/^'|'$/g, '')).filter(Boolean)
const limitsBlock = grab(/export const EVENT_PROPERTY_LIMITS = \{([\s\S]*?)\} as const;/, 'EVENT_PROPERTY_LIMITS')
const limits = {}
for (const line of limitsBlock.split('\n')) {
  const m = line.match(/^\s*(\w+):\s*(\d+),?/)
  if (m) limits[m[1]] = Number(m[2])
}
const eventsBlock = grab(/export const MUSHI_EVENTS = \{([\s\S]*?)\} as const;/, 'MUSHI_EVENTS')
const quotedList = (s) => s.split(',').map((x) => x.trim().replace(/^'|'$/g, '')).filter(Boolean)
const events = []
for (const line of eventsBlock.split('\n')) {
  // An entry line that fails the shape must stop the build: a skipped line
  // would drop the event from the edge-function mirror without a trace.
  if (!/^\s*[a-z][a-z0-9_]*:\s*\{/.test(line)) continue
  const m = line.match(
    /^\s*([a-z][a-z0-9_]*):\s*\{\s*surface:\s*('\w+'|\[[^\]]*\]),\s*required:\s*\[([^\]]*)\]\s*\},?\s*$/,
  )
  if (!m) throw new Error(`gen-analytics-taxonomy: cannot parse MUSHI_EVENTS entry: ${line.trim()}`)
  const surfaceList = quotedList(m[2].replace(/^\[|\]$/g, ''))
  for (const s of surfaceList) {
    if (!surfaces.includes(s)) throw new Error(`gen-analytics-taxonomy: ${m[1]} uses unknown surface '${s}'`)
  }
  const surface = m[2].startsWith('[') ? surfaceList : surfaceList[0]
  events.push({ name: m[1], surface, required: quotedList(m[3]) })
}
if (events.length === 0) throw new Error('gen-analytics-taxonomy: parsed zero events')
const activation = grab(/export const ACTIVATION_EVENT: MushiEventName = '(\w+)';/, 'ACTIVATION_EVENT')
const habit = quotedList(grab(/export const HABIT_EVENTS: readonly MushiEventName\[\] = \[([^\]]*)\];/, 'HABIT_EVENTS'))
for (const h of habit) {
  if (!events.some((e) => e.name === h)) throw new Error(`gen-analytics-taxonomy: HABIT_EVENTS names unknown event '${h}'`)
}

const body = `/**
 * FILE: analytics-taxonomy.generated.ts
 * GENERATED by scripts/gen-analytics-taxonomy.mjs from
 * packages/core/src/analytics-taxonomy.ts — DO NOT EDIT BY HAND.
 * Run \`node scripts/gen-analytics-taxonomy.mjs\` after changing the source.
 */

export const EVENT_NAME_RE = ${nameRe}
export const PII_PROPERTY_KEY_RE = ${piiRe}
export const RESERVED_PROPERTY_PREFIX = '$'

export const EVENT_PROPERTY_LIMITS = ${JSON.stringify(limits, null, 2)} as const

export const MUSHI_SURFACES = ${JSON.stringify(surfaces)} as const
export type MushiSurface = (typeof MUSHI_SURFACES)[number]

export const MUSHI_EVENTS = ${JSON.stringify(
  Object.fromEntries(events.map((e) => [e.name, { surface: e.surface, required: e.required }])),
  null,
  2,
)} as const

export type MushiEventName = keyof typeof MUSHI_EVENTS
export const MUSHI_EVENT_NAMES = Object.keys(MUSHI_EVENTS) as MushiEventName[]
export const ACTIVATION_EVENT: MushiEventName = '${activation}'

export function isValidEventName(name: unknown): name is string {
  return typeof name === 'string' && EVENT_NAME_RE.test(name)
}
`

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== body) {
    console.error(`analytics taxonomy mirror is stale: run node scripts/gen-analytics-taxonomy.mjs`)
    process.exit(1)
  }
  console.log('analytics taxonomy mirror: OK')
} else {
  writeFileSync(OUT, body, 'utf8')
  console.log(`wrote ${OUT} (${events.length} events)`)
}
